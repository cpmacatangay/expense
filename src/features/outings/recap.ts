import { format } from 'date-fns'
import { formatCentavos } from '../../lib/money/centavos'
import type { OutingBundle } from '../../lib/types'

export function outingDateLabel(date: string): string {
  const parsed = new Date(`${date}T00:00:00`)
  return Number.isNaN(parsed.getTime()) ? date : format(parsed, 'MMM d, yyyy')
}

export function buildRecapText(bundle: OutingBundle): string {
  const { outing, members, students, coverage, shares } = bundle
  const membersById = Object.fromEntries(members.map((member) => [member.id, member]))
  const studentsById = Object.fromEntries(students.map((student) => [student.id, student]))
  const payer = membersById[outing.payerId]?.name ?? '—'

  const lines = [
    `Salo — ${outing.place || 'Meal'}, ${outingDateLabel(outing.date)}`,
    `Total: ${formatCentavos(outing.totalCentavos)} (${outing.headcount} heads × ${formatCentavos(outing.perHeadCentavos)})`,
    `Paid by: ${payer}`,
    ''
  ]

  for (const member of members) {
    const share = shares.find((item) => item.memberId === member.id)
    const covered = coverage
      .filter((item) => item.memberId === member.id)
      .map((item) => studentsById[item.studentId]?.name)
      .filter(Boolean)
      .join(', ')
    lines.push(
      `${member.name}: ${formatCentavos(share?.amountCentavos ?? 0)} — covered ${covered || 'none'}`
    )
  }

  const settlements = shares
    .filter((share) => !share.isPayer && share.amountCentavos > 0)
    .map(
      (share) =>
        `${membersById[share.memberId]?.name ?? '—'} → ${payer}: ${formatCentavos(share.amountCentavos)}`
    )

  if (settlements.length > 0) {
    lines.push('', 'Settle up:', ...settlements)
  } else {
    lines.push('', 'All settled.')
  }

  lines.push('', 'Generated by Salo. Receipts stay on our devices.')
  return lines.join('\n')
}

export function recapFilename(bundle: OutingBundle): string {
  const place = (bundle.outing.place || 'meal').toLowerCase().replace(/[^a-z0-9]+/g, '-')
  return `salo-${bundle.outing.date}-${place || 'meal'}.png`
}
